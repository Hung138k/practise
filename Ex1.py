"""
Ex1 xây dưng 1 chương trình máy tính +, - ,* , /
"""

print("a = ")
a = int(input())

print("b = ")
b = int(input())

print(str(a) + " + " + str(b) + " = " + str(a + b))

print(str(a) + " - " + str(b) + " = " + str(a - b))

print(str(a) + " * " + str(b) + " = " + str(a * b))

print(str(a) + " / " + str(b) + " = " + str(a / b))

print(str(a) + " % " + str(b) + " = " + str(a % b))